export function categorizeTide(height: number, timeWindow: string): TideCategory {
  if (timeWindow.toLowerCase().includes('não haverá') || height >= 0.8) {
    return 'nao_recomendado';
  }
  if (height <= 0.5) {
    return 'melhor'; // 0.0 a 0.5: Verde melhores dias
  }
  if (height <= 0.7) {
    return 'atencao'; // 0.6 a 0.7: Amarelo ainda dá pra fazer
  }
  return 'nao_recomendado'; // 0.8 em diante: Não recomendamos (Vermelho)
}

